// Turns supabase/data/paint_colors.json into a SQL migration that upserts the catalog.
//
// The JSON file is the source of truth for the paint catalog. To change the
// catalog: edit the JSON, then run
//   node scripts/build-paint-migration.mjs <timestamp>_<name>.sql
// to write a NEW migration (never edit one that has already been applied).
import { readFileSync, writeFileSync } from 'node:fs'

const FAMILIES = [
  'white',
  'off_white',
  'gray',
  'greige',
  'beige',
  'brown',
  'black',
  'blue',
  'green',
  'yellow',
  'orange',
  'red',
  'pink',
  'purple',
]
const BRANDS = ['benjamin_moore', 'sherwin_williams']

const fileName = process.argv[2]
if (!fileName || !/^\d{14}_[a-z0-9_]+\.sql$/.test(fileName)) {
  console.error('Usage: node scripts/build-paint-migration.mjs <YYYYMMDDHHMMSS>_<name>.sql')
  process.exit(1)
}

const colors = JSON.parse(readFileSync('supabase/data/paint_colors.json', 'utf8'))
const quote = (value) => `'${String(value).replace(/'/g, "''")}'`

const seen = new Set()
const position = new Map()
const rows = colors.map((color) => {
  const key = `${color.brand}|${color.code}`
  if (seen.has(key)) throw new Error(`Duplicate color ${key}`)
  seen.add(key)
  if (!BRANDS.includes(color.brand)) throw new Error(`Unknown brand for ${key}`)
  if (!FAMILIES.includes(color.family)) throw new Error(`Unknown family for ${key}`)
  if (!/^#[0-9A-F]{6}$/.test(color.hex)) throw new Error(`Bad hex for ${key}: ${color.hex}`)
  // sort_order follows the order in the JSON file, per brand (most popular first).
  const order = (position.get(color.brand) ?? 0) + 10
  position.set(color.brand, order)
  return `  (${quote(color.brand)}, ${quote(color.name)}, ${quote(color.code)}, ${quote(color.hex)}, ${quote(color.family)}, ${order})`
})

const sql = `-- Paint catalog: ${colors.length} popular Benjamin Moore and Sherwin-Williams colors.
-- Generated by scripts/build-paint-migration.mjs from supabase/data/paint_colors.json.
-- Hex values were read from each manufacturer's own color data and are on-screen
-- approximations of the real paint. RoomFlip is not affiliated with either brand.

insert into public.paint_colors (brand, name, code, hex, family, sort_order)
values
${rows.join(',\n')}
on conflict (brand, code) do update
set name = excluded.name,
    hex = excluded.hex,
    family = excluded.family,
    sort_order = excluded.sort_order;
`

writeFileSync(`supabase/migrations/${fileName}`, sql)
console.log(`Wrote supabase/migrations/${fileName} with ${colors.length} colors`)
